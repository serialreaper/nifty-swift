import SwiftUI

extension Font {
    static func berkshireSwash(size: CGFloat) -> Font {
        .custom("BerkshireSwash-Regular", size: size)
    }
    
    static func calSans(size: CGFloat) -> Font {
        .custom("CalSans-Regular", size: size)
    }
}
